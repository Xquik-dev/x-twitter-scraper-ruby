# frozen_string_literal: true

module XTwitterScraper
  module Models
    class SubtitleTrack < XTwitterScraper::Internal::Type::BaseModel
      # @!attribute media_key
      #   Media key of the video, as media rows carry it.
      #
      #   @return [String, nil]
      optional :media_key, String, api_name: :mediaKey

      # @!attribute language
      #   Language code of the track, in lower case.
      #
      #   @return [String, nil]
      optional :language, String

      # @!attribute name
      #   Track name the uploader or X gave it.
      #
      #   @return [String, nil]
      optional :name, String

      # @!attribute auto_generated
      #   True when X transcribed the audio itself.
      #
      #   @return [Boolean]
      required :auto_generated, XTwitterScraper::Internal::Type::Boolean, api_name: :autoGenerated

      # @!attribute url
      #   Link to the track's first WebVTT file.
      #
      #   @return [String]
      required :url, String

      # @!attribute text
      #   Every cue's text in order, as 1 line.
      #
      #   @return [String]
      required :text, String

      # @!attribute truncated
      #   True when X didn't serve every caption file of the track in time, so the cues
      #   cover only its start. Retry for the rest.
      #
      #   @return [Boolean]
      required :truncated, XTwitterScraper::Internal::Type::Boolean

      # @!attribute cues
      #   Timed captions in order.
      #
      #   @return [Array<XTwitterScraper::Models::SubtitleTrack::Cue>]
      required :cues, -> { XTwitterScraper::Internal::Type::ArrayOf[XTwitterScraper::Models::SubtitleTrack::Cue] }

      # @!method initialize(auto_generated:, url:, text:, truncated:, cues:, media_key: nil, language: nil, name: nil)
      #   Holds 1 caption track of a video.
      #
      #   @param auto_generated [Boolean] True when X transcribed the audio itself.
      #
      #   @param url [String] Link to the track's first WebVTT file.
      #
      #   @param text [String] Every cue's text in order, as 1 line.
      #
      #   @param truncated [Boolean] True when X didn't serve every caption file of the track in time, so the cues cover only its start. Retry for the rest.
      #
      #   @param cues [Array<XTwitterScraper::Models::SubtitleTrack::Cue>] Timed captions in order.
      #
      #   @param media_key [String] Media key of the video, as media rows carry it.
      #
      #   @param language [String] Language code of the track, in lower case.
      #
      #   @param name [String] Track name the uploader or X gave it.

      class Cue < XTwitterScraper::Internal::Type::BaseModel
        # @!attribute start_ms
        #   Start time in milliseconds.
        #
        #   @return [Integer]
        required :start_ms, Integer, api_name: :startMs

        # @!attribute end_ms
        #   End time in milliseconds.
        #
        #   @return [Integer]
        required :end_ms, Integer, api_name: :endMs

        # @!attribute text
        #   Caption text, with a line break between lines.
        #
        #   @return [String]
        required :text, String

        # @!method initialize(start_ms:, end_ms:, text:)
        #   @param start_ms [Integer] Start time in milliseconds.
        #
        #   @param end_ms [Integer] End time in milliseconds.
        #
        #   @param text [String] Caption text, with a line break between lines.
      end
    end
  end
end
